"""MCP Tool Module: Part VI Autonomous 'Dev Zone' & Self-Evolution Sandbox."""

from __future__ import annotations

import ast
import re
import subprocess
from datetime import datetime
from pathlib import Path
from typing import Any, Dict

from server.config import settings
from server.mcp_tools import load_all_mcp_tools, register_mcp_tool


@register_mcp_tool(
    name="generate_hud_widget",
    description="Self-Coding Loop: scaffolds a new MCP backend tool and React HUD widget snippet, runs AST syntax verification, and stages it in the Dev Zone.",
    category="Autonomous Dev Zone",
)
def generate_hud_widget(widget_name: str, description: str) -> Dict[str, Any]:
    clean_slug = re.sub(r"[^a-zA-Z0-9_]", "_", widget_name.strip().lower()).strip("_") or "custom_module"
    pascal_name = "".join(word.capitalize() for word in clean_slug.split("_"))

    py_code = f'''"""Auto-Generated MCP Tool: {pascal_name} ({description})
Generated by J.A.R.V.I.S. Self-Evolution Protocol at {datetime.now().isoformat(timespec="seconds")}
"""

from typing import Any, Dict
from server.mcp_tools import register_mcp_tool


@register_mcp_tool(
    name="run_{clean_slug}",
    description={description!r},
    category="Self-Evolved",
)
def run_{clean_slug}(query: str = "status") -> Dict[str, Any]:
    return {{
        "module": "{pascal_name}",
        "status": "operational",
        "description": {description!r},
        "query": query,
    }}
'''

    tsx_code = f"""// Auto-Generated Spatial HUD Widget: {pascal_name}Widget.tsx
// Description: {description}
import React from 'react';

export const {pascal_name}Widget: React.FC = () => {{
  return (
    <div className="p-4 text-cyan-100 font-mono space-y-2">
      <div className="text-xs uppercase tracking-widest text-cyan-400">
        Autonomous Module // {pascal_name}
      </div>
      <p className="text-sm text-slate-300">{description}</p>
      <div className="p-2 rounded bg-cyan-950/40 border border-cyan-500/30 text-xs">
        Status: Sandbox AST Verified & Hot-Reload Ready
      </div>
    </div>
  );
}};
"""

    # 1. Verify Python AST Syntax in Sandbox before writing
    ast.parse(py_code)

    # 2. Write the new MCP plugin tool into server/mcp_tools/
    target_py = settings.ROOT_DIR / "server" / "mcp_tools" / f"auto_{clean_slug}.py"
    target_py.write_text(py_code, encoding="utf-8")

    # 3. Dynamically hot-reload the MCP tool registry
    load_all_mcp_tools()

    # 4. Check git branch status if git repo exists
    git_branch = "main (sandbox-staged)"
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=str(settings.ROOT_DIR),
            capture_output=True,
            text=True,
            timeout=2,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            git_branch = proc.stdout.strip()
    except Exception:
        pass

    return {
        "hud_action": "dev_zone_updated",
        "widget_name": pascal_name,
        "tool_name": f"run_{clean_slug}",
        "python_path": str(target_py.relative_to(settings.ROOT_DIR)),
        "ast_verified": True,
        "git_branch": git_branch,
        "generated_py": py_code,
        "generated_tsx": tsx_code,
    }

